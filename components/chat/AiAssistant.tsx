function preprocessText(raw: string): string {
  let s = raw;

  // Auto-normalize any order/tracking links generated by AI to /account
  s = s.replace(/\[([^\]]*order[^\]]*)\]\((?:\/orders?|\/account\/orders?|\/order-tracking|\/track-order|\/track)[^)]*\)/gi, '[$1](/account)');
  s = s.replace(/\[([^\]]*track[^\]]*)\]\((?:\/orders?|\/account\/orders?|\/order-tracking|\/track-order|\/track)[^)]*\)/gi, '[$1](/account)');

  // Auto-link "My Account > Orders"
  if (!s.includes('](/account)')) {
    s = s.replace(/My Account\s*>\s*Orders(?:\s*page)?/gi, '[My Account > Orders](/account)');
  }

  // Auto-link order status & tracking phrases
  if (!s.includes('](/account)')) {
    s = s.replace(/\b(?:track(?:ing)?\s+(?:your\s+)?order|check\s+(?:your\s+)?order|view\s+(?:your\s+)?orders?)\b/gi, '[Track Your Order](/account)');
  }

  // Auto-link phone numbers
  if (!s.includes('](tel:')) {
    s = s.replace(/\+91\s*99948\s*47167/g, '[+91 99948 47167](tel:+919994847167)');
    s = s.replace(/\+91\s*91763\s*67777/g, '[+91 99948 47167](tel:+919994847167)');
  }
  // Auto-link emails
  if (!s.includes('](mailto:')) {
    s = s.replace(/support@intersting\.duckdns\.org/g, '[support@intersting.duckdns.org](mailto:support@intersting.duckdns.org)');
    s = s.replace(/hello@interesting\.co\.in/g, '[hello@interesting.co.in](mailto:hello@interesting.co.in)');
  }
  // Auto-link Return & Refund Policy — ONLY matches the exact phrase "Return Policy" or "Return & Refund Policy"
  if (!s.includes('](/returns)')) {
    s = s.replace(/\bReturn\s*(?:&\s*Refund\s*)?Policy\b/gi, '[Return & Refund Policy](/returns)');
  }
  // Auto-link Shipping Policy — ONLY matches the exact phrase "Shipping Policy"
  if (!s.includes('](/shipping)')) {
    s = s.replace(/\bShipping\s*(?:&\s*Delivery\s*)?Policy\b/gi, '[Shipping Policy](/shipping)');
  }
  // Auto-link FAQ & Payments — ONLY matches the uppercase abbreviation "FAQ" as a standalone word
  if (!s.includes('](/faq)')) {
    s = s.replace(/\bFAQ\b(?:\s*&\s*Payments?)?/g, '[FAQ & Payments](/faq)');
  }
  // Auto-link Terms & Privacy — ONLY matches the exact phrase "Terms & Privacy" or "Terms and Privacy"
  if (!s.includes('](/terms)')) {
    s = s.replace(/\bTerms\s*(?:&|and)\s*Privacy\b/gi, '[Terms & Privacy](/terms)');
  }
  return s;
}

function renderFormattedText(text: string, onLinkClick: () => void) {
  const processed = preprocessText(text);
  const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  const parts: React.ReactNode[] = [];
  let lastIndex = 0;
  let match: RegExpExecArray | null;

  while ((match = linkRegex.exec(processed)) !== null) {
    if (match.index > lastIndex) {
      parts.push(processed.slice(lastIndex, match.index));
    }

    const label = match[1];
    const url = match[2];

    if (url.startsWith('/')) {
      parts.push(
        <Link
          key={`link-${match.index}`}
          href={url}
          onClick={onLinkClick}
          className={styles.bubbleLink}
        >
          {label}
        </Link>
      );
    } else {
      parts.push(
        <a
          key={`link-${match.index}`}
          href={url}
          target="_blank"
          rel="noopener noreferrer"
          className={styles.bubbleLink}
        >
          {label}
        </a>
      );
    }

    lastIndex = linkRegex.lastIndex;
  }

  if (lastIndex < processed.length) {
    parts.push(processed.slice(lastIndex));
  }

  return parts.length > 0 ? parts : processed;
}

export default function AiAssistant() {
  const pathname = usePathname();
  const [isOpen, setIsOpen] = useState(false);
  const [input, setInput] = useState('');
  const [messages, setMessages] = useState<ChatMessage[]>([]);
  const [isLoading, setIsLoading] = useState(false);
  const [addedIds, setAddedIds] = useState<number[]>([]);
  const [currentOrderContext, setCurrentOrderContext] = useState<OrderContext | null>(null);

  // Hold-to-Dismiss Session State
  const [isDismissed, setIsDismissed] = useState(false);
  const [showRemoveZone, setShowRemoveZone] = useState(false);
  const holdTimerRef = useRef<NodeJS.Timeout | null>(null);
  const autoHideTimerRef = useRef<NodeJS.Timeout | null>(null);
  const isHoldingRef = useRef(false);

  // Sync with mobile bottom navigation capsule & floating cart bar
  const [isCapsuleVisible, setIsCapsuleVisible] = useState(true);
  const [isKeyboardOpen, setIsKeyboardOpen] = useState(false);
  const [visualHeight, setVisualHeight] = useState<number | null>(null);
  const lastScrollY = useRef(0);

  useEffect(() => {
    const handleScroll = () => {
      const currentScrollY = window.scrollY;
      const diff = currentScrollY - lastScrollY.current;

      if (currentScrollY < 40) {
        setIsCapsuleVisible(true);
        lastScrollY.current = currentScrollY;
        return;
      }

      if (diff > 8) {
        setIsCapsuleVisible(false);
      } else if (diff < -8) {
        setIsCapsuleVisible(true);
      }

      lastScrollY.current = currentScrollY;
    };

    const handleCapsuleEvent = (e: Event) => {
      const customEvent = e as CustomEvent<{ visible: boolean }>;
      if (customEvent.detail !== undefined) {
        setIsCapsuleVisible(customEvent.detail.visible);
      }
    };

    window.addEventListener('scroll', handleScroll, { passive: true });
    window.addEventListener('capsule-visibility', handleCapsuleEvent);
    return () => {
      window.removeEventListener('scroll', handleScroll);
      window.removeEventListener('capsule-visibility', handleCapsuleEvent);
    };
  }, []);

  const messagesListRef = useRef<HTMLDivElement>(null);
  const messagesEndRef = useRef<HTMLDivElement>(null);
  const lastActiveUserMsgIdRef = useRef<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const { addItem, openDrawer, itemCount } = useCartContext();
  const { showSuccess } = useToast();

  // Restore dismissal preference for current session
  useEffect(() => {
    try {
      if (sessionStorage.getItem('chappie_dismissed') === 'true') {
        setIsDismissed(true);
      }
    } catch {
      // Storage access check
    }
  }, []);

  const handlePointerDown = (e: React.PointerEvent) => {
    if (e.button !== 0 && e.pointerType === 'mouse') return;
    isHoldingRef.current = false;

    // Trigger bottom "X" dismiss target when held for 400ms
    holdTimerRef.current = setTimeout(() => {
      isHoldingRef.current = true;
      setShowRemoveZone(true);

      if (autoHideTimerRef.current) clearTimeout(autoHideTimerRef.current);
      autoHideTimerRef.current = setTimeout(() => {
        setShowRemoveZone(false);
      }, 5000);
    }, 400);
  };

  const handlePointerUp = () => {
    if (holdTimerRef.current) {
      clearTimeout(holdTimerRef.current);
      holdTimerRef.current = null;
    }

    // Quick tap/click: play boop reaction then open chat
    if (!isHoldingRef.current) {
      setTimeout(() => setIsOpen(true), 350);
    }
  };

  const handleDismissSession = (e: React.MouseEvent) => {
    e.stopPropagation();
    try {
      sessionStorage.setItem('chappie_dismissed', 'true');
    } catch {
      // Storage access check
    }
    setIsDismissed(true);
    setShowRemoveZone(false);
  };

  /**
   * Intelligently scrolls to a specific message so newly generated text and
   * the user's question appear right at the top of the viewport (never pushed out by cards below).
   */
  const scrollToMessage = (msgId: string, behavior: ScrollBehavior = 'smooth') => {
    if (!messagesListRef.current || typeof window === 'undefined') return;
    const container = messagesListRef.current;
    const target = document.getElementById(`msg-${msgId}`);
    if (target) {
      const containerRect = container.getBoundingClientRect();
      const targetRect = target.getBoundingClientRect();
      const targetRelativeTop = targetRect.top - containerRect.top + container.scrollTop;
      container.scrollTo({
        top: Math.max(0, targetRelativeTop - 12),
        behavior,
      });
    } else {
      messagesEndRef.current?.scrollIntoView({ behavior });
    }
  };

  const scrollToBottom = (behavior: ScrollBehavior = 'smooth') => {
    if (messagesListRef.current) {
      messagesListRef.current.scrollTo({
        top: messagesListRef.current.scrollHeight,
        behavior,
      });
    } else {
      messagesEndRef.current?.scrollIntoView({ behavior });
    }
  };

  // Mobile virtual keyboard handling and background scroll lock
  useEffect(() => {
    if (!isOpen || typeof window === 'undefined') return;

    // Lock background body scroll while chat modal is open on mobile
    const origOverflow = document.body.style.overflow;
    const isMobile = window.innerWidth <= 768;
    if (isMobile) {
      document.body.style.overflow = 'hidden';
    }

    const vv = window.visualViewport;
    const handleViewportChange = () => {
      if (!vv) return;
      const vh = vv.height;
      const keyboardActive = window.innerHeight - vh > 70;
      setIsKeyboardOpen(keyboardActive);
      setVisualHeight(vh);
      document.documentElement.style.setProperty('--chat-vh', `${vh}px`);
      // Keep active message visible right above the virtual keyboard
      setTimeout(() => {
        if (lastActiveUserMsgIdRef.current) {
          scrollToMessage(lastActiveUserMsgIdRef.current, 'smooth');
        } else {
          scrollToBottom('smooth');
        }
      }, 80);
    };

    if (vv) {
      handleViewportChange();
      vv.addEventListener('resize', handleViewportChange);
      vv.addEventListener('scroll', handleViewportChange);
    }

    return () => {
      document.body.style.overflow = origOverflow;
      document.documentElement.style.removeProperty('--chat-vh');
      if (vv) {
        vv.removeEventListener('resize', handleViewportChange);
        vv.removeEventListener('scroll', handleViewportChange);
      }
    };
  }, [isOpen]);

  useEffect(() => {
    if (isOpen) {
      if (messages.length === 0) {
        if (messagesListRef.current) messagesListRef.current.scrollTop = 0;
      } else if (lastActiveUserMsgIdRef.current) {
        scrollToMessage(lastActiveUserMsgIdRef.current, 'auto');
      } else {
        scrollToBottom('auto');
      }

      // On mobile devices, DO NOT auto-focus input so the keyboard doesn't abruptly pop up
      // and hide the welcome text and starter prompt chips! Only auto-focus on desktop keyboards.
      const isMobile = typeof window !== 'undefined' && window.innerWidth <= 768;
      if (!isMobile) {
        setTimeout(() => inputRef.current?.focus(), 150);
      }
    }
  }, [isOpen]);

  const handleSendMessage = async (textToSend?: string, orderOverride?: OrderContext | null) => {
    const text = (textToSend || input).trim();
    if (!text || isLoading) return;

    const userMsg: ChatMessage = {
      id: `user-${Date.now()}`,
      role: 'user',
      content: text,
    };
    lastActiveUserMsgIdRef.current = userMsg.id;

    setMessages((prev) => [...prev, userMsg]);
    setInput('');
    setIsLoading(true);

    // Smoothly scroll to the newly sent user message so typing indicator is visible right below
    setTimeout(() => {
      scrollToMessage(userMsg.id, 'smooth');
    }, 40);

    const activeOrder = orderOverride !== undefined ? orderOverride : currentOrderContext;

    try {
      const historyPayload = messages.slice(-4).map((m) => ({
        role: m.role,
        content: m.content,
      }));

      const res = await fetch('/api/assistant', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          message: text,
          history: historyPayload,
          order: activeOrder || undefined,
        }),
      });

      const data = await res.json();

      const assistantMsg: ChatMessage = {
        id: `assistant-${Date.now()}`,
        role: 'assistant',
        content:
          data.reply ||
          'Here are our recommendations based on our live store inventory!',
        products: Array.isArray(data.products) ? data.products : [],
        suggestions: Array.isArray(data.suggestions) ? data.suggestions : [],
      };

      setMessages((prev) => [...prev, assistantMsg]);
      setIsLoading(false);

      // Intelligently scroll to the user message so the newly generated text is front-and-center
      // and NOT scrolled past by product cards!
      setTimeout(() => {
        scrollToMessage(userMsg.id, 'smooth');
      }, 70);
    } catch (err) {
      console.error('Chat error:', err);
      const errId = `err-${Date.now()}`;
      setMessages((prev) => [
        ...prev,
        {
          id: errId,
          role: 'assistant',
          content:
            'I had a temporary hiccup retrieving recommendations. Feel free to ask again or explore our catalog directly!',
        },
      ]);
      setIsLoading(false);
      setTimeout(() => {
        scrollToMessage(userMsg.id, 'smooth');
      }, 70);
    }
  };

  const handleSendMessageRef = useRef(handleSendMessage);
  useEffect(() => {
    handleSendMessageRef.current = handleSendMessage;
  });

  // Support remote activation from "Need Help?" in My Orders or Order Details
  useEffect(() => {
    const handleOpenAssistant = (e: Event) => {
      const customEvent = e as CustomEvent<{ prompt?: string; order?: OrderContext }>;
      const detail = customEvent.detail;
      setIsOpen(true);
      setIsDismissed(false);
      if (detail?.order) {
        setCurrentOrderContext(detail.order);
      }
      if (detail?.prompt) {
        setTimeout(() => {
          handleSendMessageRef.current(detail.prompt, detail.order || null);
        }, 60);
      }
    };

    window.addEventListener('open-ai-assistant', handleOpenAssistant);
    return () => {
      window.removeEventListener('open-ai-assistant', handleOpenAssistant);
    };
  }, []);

  const handleSuggestionClick = (actionText: string) => {
    if (actionText.toLowerCase().includes('whatsapp')) {
      const orderRef = currentOrderContext ? `Order #${currentOrderContext.id}` : 'my order';
      const waText = encodeURIComponent(
        `Hi Interesting Support, I need assistance with ${orderRef}. Could you please connect me with a concierge?`
      );
      window.open(`https://wa.me/919994847167?text=${waText}`, '_blank');
      return;
    }
    handleSendMessage(actionText.replace(/^[^\w]+/, '').trim());
  };

  const handleAddToCart = (product: RetrievedProduct, e?: React.MouseEvent) => {
    if (e) {
      flyToCart(e, product.image);
    }
    addItem({
      id: product.id,
      productId: product.id,
      name: product.name,
      slug: product.slug,
      price: product.price,
      image: product.image,
      stockStatus: (product.stock_status as 'instock' | 'outofstock') || 'instock',
    });

    setAddedIds((prev) => [...prev, product.id]);
    showSuccess(`Added "${product.name}" to your bag!`);
  };

  const hasCart = itemCount > 0;
  const positionClass = hasCart
    ? isCapsuleVisible
      ? styles.posCartWithCapsule
      : styles.posCartWithoutCapsule
    : isCapsuleVisible
    ? styles.posEmptyWithCapsule
    : styles.posEmptyWithoutCapsule;

  // Automatically hide AI assistant on checkout / payment pages to avoid blocking payment buttons and radio options
  if (pathname?.startsWith('/checkout')) {
    return null;
  }

  return (
    <>
      {/* 1. Interactive Cursor-Tracking Mascot Trigger */}
      {!isOpen && !isDismissed && (
        <div
          className={`${styles.mascotTriggerContainer} ${positionClass}`}
          onPointerDown={handlePointerDown}
          onPointerUp={handlePointerUp}
          onPointerCancel={() => {
            if (holdTimerRef.current) clearTimeout(holdTimerRef.current);
          }}
          title="Click to chat • Hold to remove for this session"
        >
          {/* Floating Speech Pill Badge */}
          <button
            type="button"
            className={styles.speechPill}
            aria-label="Ask Chappie AI"
          >
            <span className={styles.onlinePulseDot} />
            <span className={styles.speechText}>Ask Chappie AI</span>
            <Sparkles size={13} className={styles.sparkleIcon} />
          </button>

          {/* Interactive Mascot that follows cursor and reacts */}
          <div className={styles.mascotFloatWrap}>
            <div className={styles.mascotScale}>
              <Mascot
                directions="/mascots/toaster-directions.webp"
                reactions="/mascots/toaster-reactions.webp"
                size={82}
                label="Chappie AI Mascot"
              />
            </div>
            <div className={styles.groundShadow} />
          </div>
        </div>
      )}

      {/* Bottom Session Dismiss Target (Revealed when user holds Chappie) */}
      {showRemoveZone && !isDismissed && !isOpen && (
        <div className={styles.bottomDismissOverlay}>
          <button
            type="button"
            className={styles.bottomDismissBtn}
            onClick={handleDismissSession}
            aria-label="Remove Chappie for this session"
          >
            <div className={styles.dismissCircle}>
              <X size={18} strokeWidth={2.5} />
            </div>
            <span className={styles.dismissLabel}>Remove Chappie for this session</span>
          </button>
          <button
            type="button"
            className={styles.dismissCancelBtn}
            onClick={(e) => {
              e.stopPropagation();
              setShowRemoveZone(false);
            }}
          >
            Keep
          </button>
        </div>
      )}

      {/* 2. Interactive Chat Window */}
      {isOpen && (
        <div
          className={styles.chatWindow}
          style={visualHeight && typeof window !== 'undefined' && window.innerWidth <= 768 ? { height: `${visualHeight}px` } : undefined}
          role="dialog"
          aria-modal="true"
        >
          {/* Header */}
          <div className={styles.chatHeader}>
            <div className={styles.headerInfo}>
              <div className={styles.avatarWrap}>
                <Mascot
                  directions="/mascots/toaster-directions.webp"
                  reactions="/mascots/toaster-reactions.webp"
                  size={36}
                  label="Chappie AI Mascot"
                />
                <span className={styles.onlineDot} />
              </div>
              <div>
                <h3 className={styles.headerTitle}>Chappie • AI Nutritionist</h3>
                <p className={styles.headerSub}>Farm-Fresh Wellness Concierge • Interesting Pantry</p>
              </div>
            </div>

            <button
              type="button"
              onClick={() => setIsOpen(false)}
              className={styles.closeBtn}
              aria-label="Close chat"
            >
              <X size={18} />
            </button>
          </div>

          {/* Active Order Context Banner */}
          {currentOrderContext && (
            <div className={styles.chatOrderContextBar}>
              <div className={styles.chatOrderContextInfo}>
                <Package size={14} className={styles.chatOrderContextIcon} />
                <span className={styles.chatOrderContextId}>Order #{currentOrderContext.id}</span>
                <span className={styles.chatOrderContextBadge}>{currentOrderContext.status}</span>
                <span className={styles.chatOrderContextTotal}>{currentOrderContext.total}</span>
              </div>
              <a
                href={`https://wa.me/919994847167?text=${encodeURIComponent(
                  `Hi Interesting Support, I need help with Order #${currentOrderContext.id} (${currentOrderContext.status}, ${currentOrderContext.total}).`
                )}`}
                target="_blank"
                rel="noopener noreferrer"
                className={styles.chatOrderContextWhatsApp}
                title="Connect on WhatsApp"
              >
                <PhoneCall size={12} /> WhatsApp
              </a>
            </div>
          )}

          {/* Messages Body */}
          <div className={styles.messagesList} ref={messagesListRef}>
            {/* Welcome Greeting */}
            <div className={styles.welcomeCard}>
              <p style={{ margin: '0 0 0.5rem' }}>
                Hello! I&apos;m <strong>Chappie</strong>, your AI concierge for Interesting. Ask me anything about our nuts, super-seeds, dietary advice, or gift hampers!
              </p>
              <div className={styles.chipsContainer}>
                {STARTER_PROMPTS.map((prompt) => (
                  <button
                    key={prompt}
                    type="button"
                    onClick={() => handleSendMessage(prompt.replace(/^[^\w]+/, '').trim())}
                    className={styles.promptChip}
                  >
                    {prompt}
                  </button>
                ))}
              </div>
            </div>

            {/* Conversation Flow */}
            {messages.map((msg) => (
              <React.Fragment key={msg.id}>
                {msg.role === 'user' ? (
                  <div id={`msg-${msg.id}`} className={styles.userRow}>
                    <div className={styles.userBubble}>{msg.content}</div>
                  </div>
                ) : (
                  <div id={`msg-${msg.id}`} className={styles.assistantRow}>
                    {/* 1. Primary AI Text Response */}
                    <div className={styles.assistantBubble}>
                      {renderFormattedText(msg.content, () => setIsOpen(false))}
                    </div>

                    {/* 2. Direct Matching Product Recommendation Cards */}
                    {msg.products && msg.products.length > 0 && (
                      <div className={styles.productCardsStrip}>
                        {msg.products.map((p) => {
                          const isAdded = addedIds.includes(p.id);
                          return (
                            <div key={p.id} className={styles.chatProductCard}>
                              <div className={styles.chatProductThumb}>
                                <Image
                                  src={p.image}
                                  alt={p.name}
                                  fill
                                  sizes="44px"
                                  style={{ objectFit: 'cover' }}
                                  unoptimized
                                />
                              </div>

                              <div className={styles.chatProductInfo}>
                                <Link
                                  href={`/product/${p.slug}`}
                                  className={styles.chatProductName}
                                  title={p.name}
                                  onClick={() => setIsOpen(false)}
                                >
                                  {p.name}
                                </Link>
                                <span className={styles.chatProductPrice}>
                                  {formatPrice(p.price)}
                                </span>
                              </div>

                              <button
                                type="button"
                                onClick={(e) => handleAddToCart(p, e)}
                                className={styles.chatAddBtn}
                              >
                                {isAdded ? (
                                  <>
                                    <Check size={12} /> Added
                                  </>
                                ) : (
                                  <>
                                    <ShoppingBag size={12} /> Add
                                  </>
                                )}
                              </button>
                            </div>
                          );
                        })}
                      </div>
                    )}

                    {/* 3. Escalate to WhatsApp if order query isn't resolved */}
                    {currentOrderContext && (
                      <div className={styles.chatEscalateCard}>
                        <div className={styles.chatEscalateContent}>
                          <span className={styles.chatEscalateTitle}>Still need assistance?</span>
                          <span className={styles.chatEscalateDesc}>
                            If our automated concierge didn&apos;t fully answer your question, connect directly with our support team on WhatsApp.
                          </span>
                        </div>
                        <a
                          href={`https://wa.me/919994847167?text=${encodeURIComponent(
                            `Hi Interesting Support, I need human assistance regarding Order #${currentOrderContext.id} (${currentOrderContext.status}, ${currentOrderContext.total}).`
                          )}`}
                          target="_blank"
                          rel="noopener noreferrer"
                          className={styles.chatEscalateWhatsAppBtn}
                        >
                          <PhoneCall size={13} /> Chat on WhatsApp
                        </a>
                      </div>
                    )}

                    {/* 4. Quick Action Suggestion Cards / Pills (Placed below products for next questions) */}
                    {msg.suggestions && msg.suggestions.length > 0 && (
                      <div className={styles.actionCardsGrid}>
                        {msg.suggestions.map((actionText) => (
                          <button
                            key={actionText}
                            type="button"
                            onClick={() => handleSuggestionClick(actionText)}
                            className={styles.actionCardBtn}
                          >
                            {actionText}
                          </button>
                        ))}
                      </div>
                    )}
                  </div>
                )}
              </React.Fragment>
            ))}

            {/* Typing Indicator */}
            {isLoading && (
              <div className={styles.typingIndicator}>
                <span className={styles.typingDot} />
                <span className={styles.typingDot} />
                <span className={styles.typingDot} />
              </div>
            )}

            <div ref={messagesEndRef} />
          </div>

          {/* Footer Input */}
          <div className={`${styles.chatFooter} ${isKeyboardOpen ? styles.chatFooterKeyboard : ''}`}>
            <form
              onSubmit={(e) => {
                e.preventDefault();
                handleSendMessage();
              }}
              className={styles.inputForm}
            >
              <input
                ref={inputRef}
                type="text"
                value={input}
                onChange={(e) => setInput(e.target.value)}
                onFocus={() => {
                  setIsKeyboardOpen(true);
                  setTimeout(() => {
                    if (lastActiveUserMsgIdRef.current) {
                      scrollToMessage(lastActiveUserMsgIdRef.current, 'smooth');
                    } else {
                      scrollToBottom('smooth');
                    }
                  }, 120);
                }}
                onBlur={() => {
                  setTimeout(() => {
                    if (typeof window !== 'undefined' && window.visualViewport) {
                      setIsKeyboardOpen(window.innerHeight - window.visualViewport.height > 100);
                    } else {
                      setIsKeyboardOpen(false);
                    }
                  }, 120);
                }}
                placeholder="Ask about nutrition, gifts, prices..."
                className={styles.chatInput}
                disabled={isLoading}
              />
              <button
                type="submit"
                disabled={isLoading || !input.trim()}
                className={styles.sendBtn}
                aria-label="Send message"
              >
                <Send size={16} />
              </button>
            </form>
            <div className={styles.poweredNote}>
              100% Farm-Fresh • Certified Purity • Express All-India Delivery
            </div>
          </div>
        </div>
      )}
    </>
  );
}
